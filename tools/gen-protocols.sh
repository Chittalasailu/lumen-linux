#!/bin/sh
# Generate the Python bindings for the Wayland protocols lumen-panel speaks
# beyond the core protocol, from the XML in components/lumen-panel/protocols/:
#
#   wlr-foreign-toplevel-management-unstable-v1  task list, window switcher
#   ext-workspace-v1                             workspace indicator
#
# Needs python3-pywayland (Debian) for pywayland-scanner. The output is committed,
# so building the panel does not need the scanner. Run after changing the XML.
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
SRC="$ROOT/components/lumen-panel/protocols"
OUT="$ROOT/components/lumen-panel/lumen_panel/protocols"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# The scanner resolves cross-protocol references (wl_seat, wl_output) only for
# protocols it generates in the same run, so the core protocol goes in too...
pywayland-scanner -i /usr/share/wayland/wayland.xml "$SRC"/*.xml -o "$TMP"
rm -rf "$OUT"
mkdir -p "$OUT"
for dir in "$TMP"/*/; do
    name=$(basename "$dir")
    [ "$name" = wayland ] && continue
    cp -r "$dir" "$OUT/$name"
done
# ...and its references are then pointed at the copy pywayland already ships.
find "$OUT" -name '*.py' -exec sed -i 's/^from \.\.wayland import /from pywayland.protocol.wayland import /' {} +
# ext_workspace_handle_v1 and ext_workspace_group_handle_v1 import each other, which
# Python cannot load. The handle's only use of the group is the argument type of
# its `assign` request (unused here); an untyped object argument is valid for
# libwayland, so drop that import to break the cycle.
sed -i -e '/^from \.ext_workspace_group_handle_v1 import /d' \
       -e 's/interface=ExtWorkspaceGroupHandleV1/interface=None/' \
       -e 's/workspace_group: ExtWorkspaceGroupHandleV1/workspace_group: object/' \
       "$OUT/ext_workspace_v1/ext_workspace_handle_v1.py"
printf '"""Generated by tools/gen-protocols.sh from components/lumen-panel/protocols/*.xml. Do not edit."""\n' > "$OUT/__init__.py"
echo "wrote $OUT"
